#!/bin/bash

# Останавливать скрипт при любой ошибке
set -e

# Переход в каталог проекта
cd "$(dirname "$0")"

# Активация виртуального окружения
source venv/bin/activate

echo "================================================"
echo " Запуск автоматизированной сборки и тестов"
echo "================================================"

echo "[1/3] Статический анализ Flake8..."
python -m flake8 main.py logic.py db.py test_logic.py test_db.py

echo "[2/3] Запуск модульных тестов..."
python -m pytest -v

echo "[3/3] Генерация документации Doxygen..."
doxygen Doxyfile

echo "================================================"
echo " Все этапы успешно завершены!"
echo "================================================"
