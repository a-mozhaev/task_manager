#!/bin/bash

# Останавливать скрипт при ошибке
set -e

# Переход в каталог проекта
cd "$(dirname "$0")"

echo "========================================"
echo " Установка менеджера задач"
echo "========================================"

# Создание виртуального окружения
if [ ! -d "venv" ]; then
    echo "[1/3] Создание виртуального окружения..."
    python3.11 -m venv venv
else
    echo "[1/3] Виртуальное окружение уже существует."
fi

# Активация окружения и установка зависимостей
echo "[2/3] Установка зависимостей..."
source venv/bin/activate
python -m pip install -r requirements.txt

# Инициализация базы данных
echo "[3/3] Инициализация базы данных..."
python db.py

echo "========================================"
echo " Установка успешно завершена!"
echo "========================================"
