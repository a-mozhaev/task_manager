#!/bin/bash

# Останавливать скрипт при любой ошибке
set -e

# Переход в каталог проекта
cd "$(dirname "$0")"

# Активация виртуального окружения
source venv/bin/activate

echo "========================================"
echo " Автоматизированная проверка проекта"
echo "========================================"

echo "[1/2] Статический анализ Flake8..."
python -m flake8 main.py logic.py db.py test_logic.py test_db.py

echo "[2/2] Запуск Unit-тестов..."
python -m pytest -v

echo "========================================"
echo " Все проверки успешно завершены!"
echo "========================================"
